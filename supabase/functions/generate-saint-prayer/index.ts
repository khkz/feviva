import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2';

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { saintId, forceRegenerate = false } = await req.json();

    if (!saintId) {
      return new Response(
        JSON.stringify({ error: 'saintId is required' }),
        { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const supabaseUrl = Deno.env.get('SUPABASE_URL')!;
    const supabaseKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
    const lovableApiKey = Deno.env.get('LOVABLE_API_KEY');

    if (!lovableApiKey) {
      return new Response(
        JSON.stringify({ error: 'LOVABLE_API_KEY is not configured' }),
        { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const supabase = createClient(supabaseUrl, supabaseKey);

    // Fetch saint data
    const { data: saint, error: saintError } = await supabase
      .from('calendar_saints')
      .select('*')
      .eq('id', saintId)
      .single();

    if (saintError || !saint) {
      return new Response(
        JSON.stringify({ error: 'Saint not found', details: saintError }),
        { status: 404, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    // Skip if already has prayer and not forcing regeneration
    if (saint.prayer_id && !forceRegenerate) {
      return new Response(
        JSON.stringify({ 
          success: true, 
          message: 'Saint already has prayer',
          saintId: saint.id,
          prayerId: saint.prayer_id,
          skipped: true
        }),
        { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const countryInfo = saint.country_code 
      ? `Es el patrono de un país, así que incluye peticiones por la nación, su pueblo y sus gobernantes.`
      : '';

    const systemPrompt = `Eres un experto en liturgia y oración católica. Escribes oraciones que siguen la tradición de la Iglesia, son respetuosas, 
y ayudan a los fieles a conectar con Dios a través de la intercesión de los santos. 
Las oraciones deben ser en español de América Latina, con un tono reverente pero accesible.`;

    const userPrompt = `Escribe una oración católica para invocar la intercesión de ${saint.name}.

Información del santo:
- Festividad: ${saint.feast_day} de ${getMonthName(saint.feast_month)}
- Categoría: ${saint.category}
${saint.tags ? `- Características: ${saint.tags.join(', ')}` : ''}
${saint.description ? `- Breve biografía: ${saint.description.substring(0, 200)}...` : ''}
${countryInfo}

La oración debe:
1. Comenzar invocando al santo por su nombre
2. Mencionar algún aspecto de su vida o virtudes
3. Pedir su intercesión para necesidades específicas relacionadas con su vida
4. Terminar con "Amén"

Longitud: 100-200 palabras. No uses viñetas ni encabezados, escribe la oración de forma continua.`;

    console.log(`Generating prayer for saint: ${saint.name}`);

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${lovableApiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: userPrompt },
        ],
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error("AI API error:", response.status, errorText);
      
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: 'Rate limit exceeded, please try again later' }),
          { status: 429, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: 'Payment required for AI service' }),
          { status: 402, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
      
      return new Response(
        JSON.stringify({ error: 'AI API error', details: errorText }),
        { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const aiResponse = await response.json();
    const generatedPrayer = aiResponse.choices?.[0]?.message?.content;

    if (!generatedPrayer) {
      return new Response(
        JSON.stringify({ error: 'No content generated by AI' }),
        { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    // Create prayer in oraciones table
    const { data: newPrayer, error: prayerError } = await supabase
      .from('oraciones')
      .insert({
        nombre: `Oración a ${saint.name}`,
        texto: generatedPrayer.trim(),
        categoria: 'santos',
        subcategoria: saint.category === 'patron_country' ? 'patronos' : 'santos',
        tagline: `Oración para pedir la intercesión de ${saint.name}`,
        tags: saint.tags || [],
        language: 'es',
      })
      .select()
      .single();

    if (prayerError || !newPrayer) {
      console.error("Error creating prayer:", prayerError);
      return new Response(
        JSON.stringify({ error: 'Failed to create prayer', details: prayerError }),
        { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    // Update saint with prayer_id
    const { error: updateError } = await supabase
      .from('calendar_saints')
      .update({ prayer_id: newPrayer.id })
      .eq('id', saintId);

    if (updateError) {
      console.error("Error updating saint with prayer_id:", updateError);
      // Prayer was created, just failed to link - not critical
    }

    console.log(`Successfully generated prayer for: ${saint.name}, prayer_id: ${newPrayer.id}`);

    return new Response(
      JSON.stringify({ 
        success: true, 
        saintId: saint.id,
        saintName: saint.name,
        prayerId: newPrayer.id,
        prayerLength: generatedPrayer.length
      }),
      { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    );

  } catch (error) {
    console.error("Error in generate-saint-prayer:", error);
    return new Response(
      JSON.stringify({ error: error instanceof Error ? error.message : 'Unknown error' }),
      { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    );
  }
});

function getMonthName(month: number): string {
  const months = [
    'Enero', 'Febrero', 'Marzo', 'Abril', 'Mayo', 'Junio',
    'Julio', 'Agosto', 'Septiembre', 'Octubre', 'Noviembre', 'Diciembre'
  ];
  return months[month - 1] || '';
}
