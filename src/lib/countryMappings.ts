export const monthNamesShort = [
  'Ene', 'Feb', 'Mar', 'Abr', 'May', 'Jun',
  'Jul', 'Ago', 'Sep', 'Oct', 'Nov', 'Dic'
];

export function formatFeastDate(month: number, day: number, short = false): string {
  const months = short ? monthNamesShort : monthNames;
  return `${day} de ${months[month - 1]}`;
}

export function getCountryContinent(countryCode: string): string | null {
  for (const [continent, countries] of Object.entries(continentCountries)) {
    if (countries.includes(countryCode)) return continent;
  }
  return null;
}
